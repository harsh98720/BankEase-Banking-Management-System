CREATE TABLE customers (
    customer_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR2(100) NOT NULL,
    email VARCHAR2(120) UNIQUE,
    phone VARCHAR2(20),
    address VARCHAR2(250),
    created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE accounts (
    account_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id NUMBER NOT NULL REFERENCES customers(customer_id),
    account_type VARCHAR2(10) NOT NULL CHECK (account_type IN ('SAVINGS','CURRENT')),
    balance NUMBER(14,2) DEFAULT 0 NOT NULL CHECK (balance >= 0),
    status VARCHAR2(10) DEFAULT 'ACTIVE' NOT NULL CHECK (status IN ('ACTIVE','CLOSED')),
    opened_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE transactions (
    transaction_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_type VARCHAR2(12) NOT NULL CHECK (transaction_type IN ('OPENING','DEPOSIT','WITHDRAW','TRANSFER_IN','TRANSFER_OUT')),
    amount NUMBER(14,2) NOT NULL CHECK (amount > 0),
    from_account_id NUMBER REFERENCES accounts(account_id),
    to_account_id NUMBER REFERENCES accounts(account_id),
    note VARCHAR2(250),
    created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE INDEX idx_accounts_customer ON accounts(customer_id);
CREATE INDEX idx_transactions_from ON transactions(from_account_id);
CREATE INDEX idx_transactions_to ON transactions(to_account_id);

CREATE OR REPLACE VIEW v_account_summary AS
SELECT a.account_id, c.customer_id, c.full_name, c.phone, c.email,
       a.account_type, a.balance, a.status, a.opened_at
FROM accounts a JOIN customers c ON c.customer_id = a.customer_id;

CREATE OR REPLACE VIEW v_transaction_history AS
SELECT transaction_id, transaction_type, amount, from_account_id,
       to_account_id, note, created_at
FROM transactions;
